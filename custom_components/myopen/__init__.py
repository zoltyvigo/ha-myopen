"""The myOpen (itsoft) integration."""
from __future__ import annotations

from homeassistant.config_entries import ConfigEntry
from homeassistant.const import Platform
from homeassistant.core import HomeAssistant

from .const import DOMAIN
from .coordinator import MyOpenCoordinator

PLATFORMS: list[Platform] = [Platform.BUTTON]

type MyOpenConfigEntry = ConfigEntry[MyOpenCoordinator]


async def async_setup_entry(hass: HomeAssistant, entry: MyOpenConfigEntry) -> bool:
    """Set up myOpen from a config entry."""
    coordinator = MyOpenCoordinator(hass, entry)
    await coordinator.async_config_entry_first_refresh()

    entry.runtime_data = coordinator
    hass.data.setdefault(DOMAIN, {})[entry.entry_id] = coordinator

    await hass.config_entries.async_forward_entry_setups(entry, PLATFORMS)
    return True


async def async_unload_entry(hass: HomeAssistant, entry: MyOpenConfigEntry) -> bool:
    """Unload a config entry."""
    unload_ok = await hass.config_entries.async_unload_platforms(entry, PLATFORMS)
    if unload_ok:
        hass.data[DOMAIN].pop(entry.entry_id, None)
    return unload_ok
